export function resolveTools(toolNames?: string[] | null): ToolDefinition[] {
  const list = Array.isArray(toolNames) ? toolNames : DEFAULT_TOOLS;
  const resolved: ToolDefinition[] = [];
  const seen = new Set<ToolId>();

  for (const raw of list) {
    const normalized = String(raw).trim().toLowerCase();
    const match = (Object.values(TOOLS_MAP) as ToolDefinition[]).find(
      (t) => t.id.toLowerCase() === normalized || t.name.toLowerCase() === normalized
    );
    if (match && !seen.has(match.id)) {
      seen.add(match.id);
      resolved.push(match);
    }
  }

  return resolved;
}
